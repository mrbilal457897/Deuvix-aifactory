const D_MARK = `<rect x="-0.75" y="-0.5" width="95.62" height="94" fill="none"/>${dPaths
  .map((p) => p.replaceAll("{A}", ACCENT))
  .join("")}`;

async function run() {
  // Full wordmark, light ink on transparent (for light backgrounds)
  await sharp(Buffer.from(renderWordmark(INK_LIGHTBG)))
    .resize({ width: 1200 })
    .png()
    .toFile(path.join(root, "public", "images", "logo-light.png"));

  // Full wordmark, light ink on transparent (for dark backgrounds)
  await sharp(Buffer.from(renderWordmark(INK_DARKBG)))
    .resize({ width: 1200 })
    .png()
    .toFile(path.join(root, "public", "images", "logo-dark.png"));

  // Apple touch icon: 180x180, D mark on #0a0d0b with 20% padding
  const size = 180;
  const pad = Math.round(size * 0.2); // 36px
  const contentSize = size - pad * 2; // 108px
  const markW = 95.62;
  const markH = 94;
  const scale = Math.min(contentSize / markW, contentSize / markH);
  const dw = markW * scale;
  const dh = markH * scale;
  const ox = (size - dw) / 2;
  const oy = (size - dh) / 2;
  const dMarkSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="#0a0d0b"/><g transform="translate(${ox.toFixed(2)} ${oy.toFixed(2)}) scale(${scale.toFixed(4)})">${dPaths
    .map((p) => p.replaceAll("{A}", ACCENT))
    .join("")}</g></svg>`;
  await sharp(Buffer.from(dMarkSvg)).png().toFile(path.join(root, "src", "app", "apple-icon.png"));

  console.log("Wrote public/images/logo-light.png, public/images/logo-dark.png, src/app/apple-icon.png");
}

run().catch((err) => {
  console.error("export-logo failed:", err);
  process.exit(1);
});
